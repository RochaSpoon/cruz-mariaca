// Content checks that run before every build. Fails on rule violations, writes REVIEW.md.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import YAML from 'yaml';

const ROOT = new URL('../src/content/', import.meta.url).pathname;
const LEVELS = ['dogma', 'definitive', 'authoritative', 'discipline', 'opinion'];
const MYTH_SECTIONS = ['The claim', 'Why people believe it', 'What the Church teaches', 'Scripture', 'Magisterium', 'Historical record', 'The strongest remaining objection'];
const BANNED = [/\bjourney/i, /\bunlock/i, /\bdive in\b/i, /\belevate/i, /\bempower/i, /\bseamless/i, /\bdelve/i, /\btapestry/i, /in today'?s world/i, /it'?s not just\b/i, /\bnot just [^.]{1,60}, it'?s\b/i];

const walk = (d) => readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(ROOT).filter((f) => /\.mdx?$/.test(f));

const errors = [];
const lessonStats = { total: 0, full: 0, verify: [] };
const review = []; // { file, kind, text }
for (const file of files) {
  const rel = relative(ROOT, file);
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) { errors.push(`${rel}: missing frontmatter`); continue; }
  let fm;
  try { fm = YAML.parse(m[1]); } catch (e) { errors.push(`${rel}: bad frontmatter (${e.message})`); continue; }
  const body = m[2];

  for (const k of ['title', 'summary', 'reviewed', 'sources']) if (fm[k] === undefined) errors.push(`${rel}: frontmatter field "${k}" is required`);
  if (!Array.isArray(fm.sources) || fm.sources.length === 0) errors.push(`${rel}: sources[] is empty`);
  const isLesson = rel.startsWith('lessons/');
  if (!isLesson && fm.authority_level !== undefined && !LEVELS.includes(fm.authority_level)) errors.push(`${rel}: authority_level must be one of ${LEVELS.join(', ')}`);

  // Quoted Scripture is not site copy, so it is left out of the style checks.
  const lint = (rel.startsWith('daily/') ? raw.replace(/^reading_text: .*$/m, '') : raw).replace(/^> .*$/gm, '');
  if (lint.includes('\u2014')) errors.push(`${rel}: contains an em dash`);
  for (const re of BANNED) { const hit = lint.match(re); if (hit) errors.push(`${rel}: banned phrase "${hit[0]}"`); }

  if (rel.startsWith('myths/')) {
    const heads = [...body.matchAll(/^## (.+)$/gm)].map((x) => x[1].trim());
    if (JSON.stringify(heads) !== JSON.stringify(MYTH_SECTIONS)) errors.push(`${rel}: sections must be exactly, in order: ${MYTH_SECTIONS.join(' | ')}. Found: ${heads.join(' | ')}`);
    if (!fm.claim) errors.push(`${rel}: "claim" is required`);
  }

  // Review inventory
  const unverified = (fm.sources ?? []).filter((s) => !s.verified);
  const needs = [...raw.matchAll(/^.*\[NEEDS SOURCE\].*$/gm)].map((x) => x[0].trim());
  const quotes = [...body.matchAll(/<Scripture\s+cite="([^"]+)"(?![^>]*\bchecked\b)[^>]*>/g)].map((x) => x[1]);
  const done = new Set(fm.checked_quotes ?? []);
  const inlineQuotes = body.split('\n').filter((l) => !l.startsWith('>') && !l.startsWith('<')).flatMap((l) => [...l.matchAll(/"([^"]{4,120})"/g)].map((x) => x[1])).filter((q) => !done.has(q));
  const teachings = [...body.matchAll(/<Teaching\s+level="([^"]+)"/g)].map((x) => x[1]);
  if (isLesson) { lessonStats.total++; if (fm.type === 'full') lessonStats.full++; for (const l of raw.split('\n')) if (l.includes('[VERIFY')) lessonStats.verify.push(`${fm.title}: ${l.trim().slice(0, 140)}`); if (fm.type === 'full' && raw.includes('[TO WRITE]')) errors.push(`${rel}: full lesson still has [TO WRITE]`); if (fm.reviewed === true && lessonStats.verify.length) errors.push(`${rel}: reviewed is true but [VERIFY] flags remain`); continue; }
  review.push({ rel, title: fm.title, reviewed: fm.reviewed, level: fm.authority_level, unverified, needs, quotes, inlineQuotes, teachings, total: (fm.sources ?? []).length });
  if (fm.reviewed === true && (unverified.length || needs.length || quotes.length)) errors.push(`${rel}: reviewed is true but unchecked sources, quotes or [NEEDS SOURCE] markers remain`);
}

const out = [];
out.push('# REVIEW', '', 'Generated by `npm run check:content`. Do not edit by hand; fix the entry and rerun.', '');
out.push('Every entry is `reviewed: false`. Set it to `true` only after you have read the entry against its sources and cleared the items below.', '');
out.push('Douay-Rheims passages were compared with drbo.org. Catechism paragraphs, papal and conciliar documents, canon law and the Fathers cited in the written lessons were compared with the texts on vatican.va, usccb.org, newadvent.org and ccel.org. Statistics were taken from the publishing organizations. Nothing here has been reviewed by a priest or catechist.', '');
if (lessonStats.total) out.push('## Lessons', '', `${lessonStats.total} lessons in \`src/content/lessons\`: ${lessonStats.full} written in full, ${lessonStats.total - lessonStats.full} outlines with placeholders (outlines are never shown as playable). All are reviewed: false. ${lessonStats.verify.length ? 'Quotes and figures still flagged [VERIFY]:' : 'No quotes or figures are flagged for verification.'}`, '', ...lessonStats.verify.map((v) => `- ${v}`), '');
const dailyFiles = review.filter((r) => r.rel.startsWith('daily/'));
if (dailyFiles.length) out.push('## Daily Bread', '', `${dailyFiles.length} readings in \`src/content/daily\`. The scripture text was copied from drbo.org and its references are marked checked. The thoughts and questions were written for this site and need a read-through. All are reviewed: false.`, '');
for (const r of review.filter((x) => !x.rel.startsWith('daily/'))) {
  out.push(`## ${r.title}`, '', `File: \`src/content/${r.rel}\`. reviewed: ${r.reviewed}. Label: ${r.level ?? 'none'}.`, '');
  out.push(`- Sources not yet checked: ${r.unverified.length} of ${r.total}`);
  out.push(`- Douay-Rheims quotations typed from memory (compare with a source): ${r.quotes.length ? r.quotes.join('; ') : 'none'}`);
  if (r.inlineQuotes.length) out.push(`- Quoted phrases in the text to verify word for word: ${r.inlineQuotes.map((q) => '"' + q + '"').join('; ')}`);
  if (r.teachings.length) out.push(`- Authority labels on teachings to confirm with a theologian: ${r.teachings.join(', ')}`);
  out.push(`- [NEEDS SOURCE] markers: ${r.needs.length}`);
  for (const n of r.needs) out.push(`  - ${n}`);
  if (r.unverified.length) { out.push('', '<details><summary>Unchecked sources</summary>', ''); for (const s of r.unverified) out.push(`- ${s.type}: ${s.ref}${s.url ? '' : ' (no URL yet)'}`); out.push('', '</details>'); }
  out.push('');
}
writeFileSync(new URL('../REVIEW.md', import.meta.url), out.join('\n'));

if (errors.length) { console.error('Content check failed:\n' + errors.map((e) => '  - ' + e).join('\n')); process.exit(1); }
console.log(`Content check passed: ${files.length} files. REVIEW.md updated.`);
